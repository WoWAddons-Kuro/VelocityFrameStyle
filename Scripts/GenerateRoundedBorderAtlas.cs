#!/usr/bin/env dotnet run
// From repo root: dotnet run Scripts/GenerateRoundedBorderAtlas.cs
// Explicit nine-slice atlas, NOT a BackdropTemplate edgeFile strip.
// Pure BCL; no drawing library or platform-specific graphics dependency.
//
// Two rings share the bar's inner rounded rect (radius 3 UI units) and are emitted as separate 128x128 atlases:
//   rounded_border_atlas.tga  hard 4-unit black border (alpha 1 across the annulus, AA on both curves)
//   rounded_glow_atlas.tga    8-unit combat HALO centred on the border's midline (d = 2, where d is the distance
//                             outward from the bar edge), spanning d = -2 (inside the bar) to d = 6 (past the border).
//                             GAUSSIAN profile (sigma = span/6 = 1.333 units): a bright hairline at the midline with
//                             long soft tails. A quadratic hump read as a flat-topped "cylinder" (owner 2026-11-25).
// Both tables land in Assets/RoundedBorderAtlas.lua (VFS.RoundedBorderAtlas, VFS.RoundedGlowAtlas).
using System.Buffers.Binary;
using System.Text;
using System.Text.Json;

const int InnerRadiusUnits = 3, PixelsPerUnit = 4, SamplesPerAxis = 8, MiddleUnits = 2;
const int AtlasPixels = 128, CellPixels = 40, GutterPixels = 2;
string addonAssets = args.Length > 0 ? args[0] : Path.Combine("VelocityFrameStyle", "Assets");
string previewAssets = args.Length > 1 ? args[1] : "Assets";
Directory.CreateDirectory(addonAssets); Directory.CreateDirectory(previewAssets);

// Border: d in [0, 4]. Glow: d in [-2, 6], peak at d = 2 (the border's midline), half-width 4 each side.
const int BorderUnits = 4, GlowReachUnits = 2;
var borderRing = new RingSpec("rounded_border_atlas", "RoundedBorderAtlas",
    OuterUnits: BorderUnits, InnerUnits: 0, Feathered: false);
var glowRing   = new RingSpec("rounded_glow_atlas",   "RoundedGlowAtlas",
    OuterUnits: BorderUnits + GlowReachUnits, InnerUnits: GlowReachUnits, Feathered: true);
var lua = new StringBuilder();
lua.AppendLine("-- Generated by Scripts/GenerateRoundedBorderAtlas.cs; do not edit.");
lua.AppendLine("local ADDON_NAME, VFS = ...");
byte[] borderAtlas = GenerateRing(borderRing, lua);
byte[] glowAtlas = GenerateRing(glowRing, lua);

// Round shapes, WHITE with shape in alpha so the client tints them (black rim, plate-colour disc, glow colour...).
// All 128px, drawn at full size: the client scales them with SetSize. Every disc/ring the addon draws comes from here
// so nothing depends on Blizzard's TempPortraitAlphaMask (not ours, not tintable in a controlled way).
//   disc.tga          hard AA disc, radius 62px: the portrait plate and the level badge fill.
//   portrait_rim.tga  hard annulus 54..62px: the black circle surround painted OVER the portrait (hides square class
//                     icons' corners). At a 64-unit portrait drawn as 72 units the rim is ~4 units, the bar border.
//   soft_disc.tga     Gaussian disc (sigma 20px, ~0 at 62): soft plate halo behind the portrait and the combat rim glow.
const int ShapePixels = 128; double shapeR = 62, rimInner = 54, softSigma = 20;
WriteShape("disc", (d) => d <= shapeR ? 1 : 0);
WriteShape("portrait_rim", (d) => (d >= rimInner && d <= shapeR) ? 1 : 0);
WriteShape("soft_disc", (d) => d >= shapeR ? 0 : Math.Exp(-d*d/(2*softSigma*softSigma)));
lua.AppendLine("VFS.RoundedShapes = {");
lua.AppendLine("  disc = \"Interface\\\\AddOns\\\\\" .. ADDON_NAME .. \"\\\\Assets\\\\disc.tga\",");
lua.AppendLine("  portraitRim = \"Interface\\\\AddOns\\\\\" .. ADDON_NAME .. \"\\\\Assets\\\\portrait_rim.tga\",");
lua.AppendLine("  softDisc = \"Interface\\\\AddOns\\\\\" .. ADDON_NAME .. \"\\\\Assets\\\\soft_disc.tga\",");
lua.AppendLine(FormattableString.Invariant($"  pixels = {ShapePixels}, discRadius = {shapeR}, rimInnerRadius = {rimInner},"));
lua.AppendLine("}");
File.WriteAllText(Path.Combine(addonAssets, "RoundedBorderAtlas.lua"), lua.ToString());

void WriteShape(string stem, Func<double, double> coverageAtRadius)
{
    // 8x8 supersampled radial coverage from the texture centre; symmetric by construction.
    WriteTga(Path.Combine(addonAssets, stem + ".tga"), ShapePixels, ShapePixels, (x, y) =>
    {
        double sum = 0;
        for (int sy = 0; sy < SamplesPerAxis; sy++) for (int sx = 0; sx < SamplesPerAxis; sx++)
        {
            double px = x + (sx + 0.5) / SamplesPerAxis - ShapePixels / 2.0, py = y + (sy + 0.5) / SamplesPerAxis - ShapePixels / 2.0;
            sum += coverageAtRadius(Math.Sqrt(px * px + py * py));
        }
        return (255, 255, 255, (byte)Math.Round(255.0 * sum / (SamplesPerAxis * SamplesPerAxis)));
    });
    Console.WriteLine($"PASS {stem}: {ShapePixels}px white/alpha shape.");
}

byte[] GenerateRing(RingSpec spec, StringBuilder luaOut)
{
    // Corner = the extent of the CURVED region from the frame's outer edge: outer radius 3 + thickness. The inner
    // boundary of a halo (d = -InnerUnits, radius 3 - InnerUnits) ends at the same offset, so no extra allowance.
    int outerUnits = InnerRadiusUnits + spec.ThicknessUnits;
    int sourceUnits = 2 * outerUnits + MiddleUnits, sourcePixels = sourceUnits * PixelsPerUnit;
    Require(outerUnits * PixelsPerUnit + 2 * GutterPixels <= CellPixels, $"{spec.FileStem}: corner tile exceeds the {CellPixels}px cell");
    byte[] sourceAlpha = RasterRing(spec, sourceUnits, sourceUnits);
    byte[] atlasAlpha = new byte[AtlasPixels * AtlasPixels];
    int[] starts = [0, outerUnits, outerUnits + MiddleUnits];
    int[] lengths = [outerUnits, MiddleUnits, outerUnits];
    string[,] names = { {"topLeft", "top", "topRight"}, {"left", "center", "right"}, {"bottomLeft", "bottom", "bottomRight"} };
    using var metadataFile = File.Create(Path.Combine(previewAssets, spec.FileStem + ".json"));
    using var metadata = new Utf8JsonWriter(metadataFile, new JsonWriterOptions { Indented = true });
    metadata.WriteStartObject(); metadata.WriteString("texture", spec.FileStem + ".tga");
    metadata.WriteNumber("atlasPixelWidth", AtlasPixels); metadata.WriteNumber("atlasPixelHeight", AtlasPixels);
    metadata.WriteNumber("pixelsPerUiUnit", PixelsPerUnit);
    metadata.WriteNumber("thicknessUiUnits", spec.ThicknessUnits); metadata.WriteNumber("innerRadiusUiUnits", InnerRadiusUnits);
    metadata.WriteNumber("cornerUiUnits", outerUnits); metadata.WriteNumber("gutterPixels", GutterPixels);
    metadata.WriteBoolean("feathered", spec.Feathered);
    metadata.WriteNumber("minimumInnerDimension", 2 * InnerRadiusUnits);
    metadata.WriteString("uvConvention", "pixel boundaries; extruded gutters; SetTexCoord(left,right,top,bottom)");
    metadata.WriteStartArray("slices");
    luaOut.AppendLine($"VFS.{spec.LuaName} = {{");
    luaOut.AppendLine($"  texture = \"Interface\\\\AddOns\\\\\" .. ADDON_NAME .. \"\\\\Assets\\\\{spec.FileStem}.tga\",");
    luaOut.AppendLine($"  thickness = {spec.ThicknessUnits}, cornerSize = {outerUnits}, minimumInnerSize = {2*InnerRadiusUnits}, feathered = {(spec.Feathered ? "true" : "false")},");
    luaOut.AppendLine("  slices = {");
    for (int row = 0; row < 3; row++)
    for (int col = 0; col < 3; col++)
    {
        int atlasX = col * CellPixels + GutterPixels, atlasY = row * CellPixels + GutterPixels;
        int width = lengths[col] * PixelsPerUnit, height = lengths[row] * PixelsPerUnit;
        int sourceX = starts[col] * PixelsPerUnit, sourceY = starts[row] * PixelsPerUnit;
        // Extruded gutters prevent bilinear filtering from bleeding adjacent tiles.
        for (int y = -GutterPixels; y < height + GutterPixels; y++)
        for (int x = -GutterPixels; x < width + GutterPixels; x++)
            atlasAlpha[(atlasY + y) * AtlasPixels + atlasX + x] = sourceAlpha[
                (sourceY + Math.Clamp(y, 0, height - 1)) * sourcePixels + sourceX + Math.Clamp(x, 0, width - 1)];
        metadata.WriteStartObject(); metadata.WriteString("name", names[row,col]);
        metadata.WriteNumber("atlasPixelX", atlasX); metadata.WriteNumber("atlasPixelY", atlasY);
        metadata.WriteNumber("atlasPixelWidth", width); metadata.WriteNumber("atlasPixelHeight", height);
        metadata.WriteNumber("uiWidth", lengths[col]); metadata.WriteNumber("uiHeight", lengths[row]);
        metadata.WriteNumber("left", (double)atlasX / AtlasPixels);
        metadata.WriteNumber("right", (double)(atlasX + width) / AtlasPixels);
        metadata.WriteNumber("top", (double)atlasY / AtlasPixels);
        metadata.WriteNumber("bottom", (double)(atlasY + height) / AtlasPixels);
        metadata.WriteEndObject();
        luaOut.AppendLine(FormattableString.Invariant($"    {names[row,col]} = {{ {(double)atlasX/AtlasPixels}, {(double)(atlasX+width)/AtlasPixels}, {(double)atlasY/AtlasPixels}, {(double)(atlasY+height)/AtlasPixels} }},"));
    }
    WriteTga(Path.Combine(addonAssets, spec.FileStem + ".tga"), AtlasPixels, AtlasPixels, (x,y) => (255,255,255,atlasAlpha[y*AtlasPixels+x]));
    metadata.WriteEndArray(); metadata.WriteEndObject(); metadata.Flush();
    luaOut.AppendLine("  },").AppendLine("}");

    // Validate the atlas actually reconstructs the intended ring at all production heights.
    int outerPixels = spec.OuterUnits * PixelsPerUnit, centreColumn = sourcePixels / 2;
    int spanPixels = (int)(spec.SpanUnits * PixelsPerUnit);
    byte outermost = sourceAlpha[centreColumn], innermost = sourceAlpha[(spanPixels - 1) * sourcePixels + centreColumn];
    if (spec.Feathered)
    {
        Require(outermost < 16 && innermost < 16, $"{spec.FileStem}: halo must feather to ~0 at BOTH edges");
        // Span midpoint = border midline. The exact peak falls between two source rows, so each sees ~0.94.
        int peakRow = spanPixels / 2;
        Require(sourceAlpha[peakRow * sourcePixels + centreColumn] > 225, $"{spec.FileStem}: halo must peak at the border midline");
        for (int y = 1; y <= peakRow; y++)
            Require(sourceAlpha[y * sourcePixels + centreColumn] >= sourceAlpha[(y - 1) * sourcePixels + centreColumn], $"{spec.FileStem}: rise to the peak must be monotone");
        for (int y = peakRow + 1; y < spanPixels; y++)
            Require(sourceAlpha[y * sourcePixels + centreColumn] <= sourceAlpha[(y - 1) * sourcePixels + centreColumn], $"{spec.FileStem}: fall from the peak must be monotone");
    }
    else
    {
        Require(outermost == 255 && innermost == 255, $"{spec.FileStem}: hard ring must be opaque across the span");
    }
    Require(sourceAlpha[centreColumn * sourcePixels + centreColumn] == 0, $"{spec.FileStem}: centre must be transparent");
    Require(sourceAlpha.Any(a => a > 0 && a < 255), $"{spec.FileStem}: curves must contain antialias coverage");
    for (int y = 0; y < sourcePixels; y++)
    for (int x = 0; x < sourcePixels; x++)
    {
        byte a = sourceAlpha[y * sourcePixels + x];
        Require(a == sourceAlpha[y * sourcePixels + sourcePixels - 1 - x], $"{spec.FileStem}: horizontal symmetry");
        Require(a == sourceAlpha[(sourcePixels - 1 - y) * sourcePixels + x], $"{spec.FileStem}: vertical symmetry");
    }
    int[,] sizes = { {113,24}, {113,12}, {70,10}, {70,7}, {200,40}, {40,6} };
    for (int i = 0; i < sizes.GetLength(0); i++)
    {
        int outerWidth = sizes[i,0] + 2 * spec.ThicknessUnits, outerHeight = sizes[i,1] + 2 * spec.ThicknessUnits;
        byte[] direct = RasterRing(spec, outerWidth, outerHeight);
        for (int y = 0; y < outerHeight * PixelsPerUnit; y++)
        for (int x = 0; x < outerWidth * PixelsPerUnit; x++)
            Require(AtlasCoverage(atlasAlpha, outerUnits, x,y,outerWidth*PixelsPerUnit,outerHeight*PixelsPerUnit) == direct[y*outerWidth*PixelsPerUnit+x],
                $"{spec.FileStem}: nine-slice reconstruction {sizes[i,0]}x{sizes[i,1]} at {x},{y}");
    }
    Console.WriteLine($"PASS {spec.FileStem}: thickness {spec.ThicknessUnits}, corner {outerUnits}, exact nine-slice reconstruction at {sizes.GetLength(0)} sizes.");
    return atlasAlpha;
}

// A 4x display preview, composed FROM THE ATLASES (not a separate rounded-rect drawing).
// Stack: bottom border, 30%-black inner surface, green/blue fill, top border; rows 1-2 add the red ADD-blended combat glow
// at peak throb so the border/glow relationship can be judged. The glow's outer extent (6) is the OLD border extent.
const int PreviewWidth = 560, PreviewHeight = 460;
int[,] previewSizes = { {113,24}, {113,12}, {70,10}, {70,7} };
int[] rowTops = [12, 174, 280, 372];
int borderUnits = borderRing.ThicknessUnits, glowUnits = glowRing.ThicknessUnits;
WriteTga(Path.Combine(previewAssets, "rounded_border_preview.tga"), PreviewWidth, PreviewHeight, (x,y) =>
{
    double bg = ((x / 12 + y / 12) % 2 == 0) ? 0.32 : 0.45;
    double red = bg, green = bg, blue = bg;
    for (int i = 0; i < 4; i++)
    {
        // Lay every row out on the GLOW extent so the thinner border sits inset within it.
        int width = (previewSizes[i,0] + 2 * glowUnits) * PixelsPerUnit;
        int height = (previewSizes[i,1] + 2 * glowUnits) * PixelsPerUnit;
        int px = x - 16, py = y - rowTops[i];
        if (px < 0 || py < 0 || px >= width || py >= height) continue;
        int inset = (glowUnits - borderUnits) * PixelsPerUnit;
        int bw = width - 2 * inset, bh = height - 2 * inset, bx = px - inset, by = py - inset;
        bool inBorderRect = bx >= 0 && by >= 0 && bx < bw && by < bh;
        double ringAlpha = inBorderRect ? AtlasCoverage(borderAtlas, InnerRadiusUnits + borderUnits, bx,by,bw,bh) / 255.0 : 0;
        red *= 1-ringAlpha; green *= 1-ringAlpha; blue *= 1-ringAlpha;
        int edge = glowUnits * PixelsPerUnit;
        bool interior = px >= edge && px < width-edge && py >= edge && py < height-edge;
        if (interior)
        {
            red *= 0.7; green *= 0.7; blue *= 0.7;
            if (px < edge + (width - 2*edge)*0.72)
                (red,green,blue) = i % 2 == 0 ? (0.0,0.85,0.0) : (0.0,0.2,1.0);
        }
        red *= 1-ringAlpha; green *= 1-ringAlpha; blue *= 1-ringAlpha;
        if (i < 2)
        {
            double glowAlpha = AtlasCoverage(glowAtlas, InnerRadiusUnits + glowUnits, px,py,width,height) / 255.0 * 0.9;
            red = Math.Min(1, red + glowAlpha); green = Math.Min(1, green + glowAlpha * 0.1); blue = Math.Min(1, blue + glowAlpha * 0.1);
        }
    }
    return ((byte)Math.Round(red*255), (byte)Math.Round(green*255), (byte)Math.Round(blue*255), (byte)255);
});
Console.WriteLine($"Atlases + RoundedBorderAtlas.lua: {addonAssets}; preview + metadata: {previewAssets}");

static byte AtlasCoverage(byte[] atlasAlpha, int cornerUnits, int x, int y, int width, int height)
{
    int corner = cornerUnits * PixelsPerUnit;
    int col = x < corner ? 0 : x >= width-corner ? 2 : 1;
    int row = y < corner ? 0 : y >= height-corner ? 2 : 1;
    // Straight edges are uniform along their stretch axis, so any centre texel is equivalent.
    int sx = col == 0 ? x : col == 2 ? x-(width-corner) : MiddleUnits*PixelsPerUnit/2;
    int sy = row == 0 ? y : row == 2 ? y-(height-corner) : MiddleUnits*PixelsPerUnit/2;
    return atlasAlpha[(row*CellPixels+GutterPixels+sy)*AtlasPixels+col*CellPixels+GutterPixels+sx];
}

// Ring coverage from the SIGNED distance d to the bar's rounded rect (negative inside). The ring spans
// d in [-InnerUnits, OuterUnits]. Hard = 1 across the span. Feathered = Gaussian centred on the span midpoint (the
// black border's midline for the glow) with sigma = span/6, so the span ends sit at 3 sigma (alpha ~1%), renormalised
// to hit exactly 0 there. Reads as a soft glow: bright core, long tails - not a flat-topped hump.
static byte[] RasterRing(RingSpec spec, int widthUnits, int heightUnits)
{
    int width = widthUnits * PixelsPerUnit, height = heightUnits * PixelsPerUnit;
    double t = spec.OuterUnits, inner = spec.InnerUnits;
    double mid = (t - inner) / 2, half = (t + inner) / 2;
    double sigma = (t + inner) / 6, tail = Math.Exp(-(half * half) / (2 * sigma * sigma));
    byte[] alpha = new byte[width * height];
    for (int y = 0; y < height; y++)
    for (int x = 0; x < width; x++)
    {
        double covered = 0;
        for (int sy = 0; sy < SamplesPerAxis; sy++)
        for (int sx = 0; sx < SamplesPerAxis; sx++)
        {
            double px = (x + (sx+0.5)/SamplesPerAxis)/PixelsPerUnit;
            double py = (y + (sy+0.5)/SamplesPerAxis)/PixelsPerUnit;
            double d = SignedDistance(px - t, py - t, widthUnits - 2*t, heightUnits - 2*t, InnerRadiusUnits);
            if (d <= -inner || d >= t) continue;
            if (!spec.Feathered) { covered += 1; continue; }
            double g = Math.Exp(-((d - mid) * (d - mid)) / (2 * sigma * sigma));
            covered += (g - tail) / (1 - tail);
        }
        alpha[y*width+x] = (byte)Math.Round(255.0*covered/(SamplesPerAxis*SamplesPerAxis));
    }
    return alpha;
}

// Signed distance from (x,y) to the rounded rect [0,width]x[0,height] with the given corner radius; negative inside.
static double SignedDistance(double x, double y, double width, double height, double radius)
{
    double qx = Math.Abs(x - width/2) - (width/2 - radius), qy = Math.Abs(y - height/2) - (height/2 - radius);
    double ex = Math.Max(qx, 0), ey = Math.Max(qy, 0);
    return Math.Sqrt(ex*ex + ey*ey) + Math.Min(Math.Max(qx, qy), 0) - radius;
}

static void Require(bool condition, string message)
{
    if (!condition) throw new InvalidOperationException(message);
}

static void WriteTga(string path, int width, int height, Func<int,int,(byte R,byte G,byte B,byte A)> pixel)
{
    byte[] header = new byte[18]; header[2] = 2; header[16] = 32; header[17] = 0x28;
    BinaryPrimitives.WriteUInt16LittleEndian(header.AsSpan(12), (ushort)width);
    BinaryPrimitives.WriteUInt16LittleEndian(header.AsSpan(14), (ushort)height);
    using var stream = File.Create(path); stream.Write(header);
    byte[] pixels = new byte[width*height*4];
    for (int y=0; y<height; y++) for (int x=0; x<width; x++)
    {
        var color = pixel(x,y); int offset = (y*width+x)*4;
        pixels[offset]=color.B; pixels[offset+1]=color.G; pixels[offset+2]=color.R; pixels[offset+3]=color.A;
    }
    stream.Write(pixels);
}

// One emitted ring, measured by d = distance outward from the bar edge (negative = inside the bar):
// the ring covers d in [-InnerUnits, OuterUnits]. Hard rings are opaque across that span; feathered rings peak at
// the span's midpoint and fall quadratically to 0 at both ends. The frame is anchored OuterUnits beyond the bar.
record RingSpec(string FileStem, string LuaName, int OuterUnits, int InnerUnits, bool Feathered)
{
    public int ThicknessUnits => OuterUnits;             // frame offset from the bar (what the Lua `thickness` means)
    public double SpanUnits => OuterUnits + InnerUnits;  // total ring width across d
}